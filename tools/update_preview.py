"""Copy the authoritative UI into the standalone, explicitly simulated preview.

Run after editing hardware/ui. --check verifies committed preview assets match.
The production service never loads the demo transport.
"""
import argparse
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def assets():
    source = ROOT / 'hardware' / 'ui'
    html = (source / 'index.html').read_text(encoding='utf-8')
    html = html.replace('Frogdash · Driver display', 'Frogdash · Simulated design preview')
    # The simulator runs a stand-in water/meth controller with the tuning screen's own rules
    # (meth-tune.js), from its first update: in the preview that file loads with the gauges
    # instead of later (later.js). The car has a real controller and does not need it.
    assert '  "meth-tune.js",\n' in html, 'meth-tune.js is no longer in the later list'
    html = html.replace('  "meth-tune.js",\n', '')
    html = html.replace('<script src="app.js"></script>', '<script src="meth-tune.js"></script>\n<script src="demo.js"></script>\n<script src="app.js"></script>')
    # The alert catalogue: on the Pi alerts.js reads alert-rules.json from the dash; a page
    # opened from a file cannot read files, so the preview gets it as a script.
    assert '  "alerts.js"\n' in html, 'alerts.js is no longer in the later list'
    html = html.replace('  "alerts.js"\n', '  "alert-rules.js",\n  "alerts.js"\n')
    # First of all: requests to the Pi's own service fail at once, off the network.
    assert html.count('<script src="boot.js"></script>') == 1
    html = html.replace('<script src="boot.js"></script>', '<script src="offline.js"></script>\n<script src="boot.js"></script>')
    js = (source / 'app.js').read_text(encoding='utf-8')
    js = js.replace('/* Production client: values come exclusively from the local state service. */',
                    '/* Generated by tools/update_preview.py. Uses only the local demo transport. */')
    assert js.count('new WebSocket(') == 1
    js = js.replace('new WebSocket(', 'new FrogdashDemoSocket(')
    js = js.replace('WebSocket.OPEN', 'FrogdashDemoSocket.OPEN')
    css = (source / 'style.css').read_text(encoding='utf-8')
    css += '\n/* Preview-only playback controls. */\n.demo-playback { display:flex; gap:6px; }\n.demo-control { min-height:40px; padding:7px 11px; border:1px solid var(--line); border-radius:6px; background:var(--raised); color:var(--text); font-size:13px; font-weight:750; }\n.demo-control[aria-pressed=true] { border-color:var(--accent); color:var(--accent); }\n'
    demo = (ROOT / 'preview' / 'demo.js').read_text(encoding='utf-8')
    offline = (ROOT / 'preview' / 'offline.js').read_text(encoding='utf-8')
    personalize = (source / 'personalize.js').read_text(encoding='utf-8')
    extra = {name: (source / name).read_text(encoding='utf-8') for name in ('viewport.js', 'responsive.css', 'instruments.js', 'instruments.css', 'navigation.js', 'driving.js', 'trip.js', 'operations.js', 'units.js', 'review.js', 'review.css', 'camera.js', 'camera.css', 'dashcam.js', 'map.js', 'boot.js', 'taillights.js', 'taillights.css', 'taillight-settings.js', 'meth-tune.js', 'knock.js', 'knock.css', 'screen.js', 'keyboard.js', 'keyboard.css', 'summary.js', 'later.js', 'graphs.js', 'graphs.css', 'uPlot.iife.min.js', 'uPlot.min.css', 'alerts.js', 'alerts.css')}
    rules = (source / 'alert-rules.json').read_text(encoding='utf-8')
    extra['alert-rules.js'] = ('/* Generated by tools/update_preview.py from hardware/ui/alert-rules.json. */\n'
                               f'window.frogdashAlertRules = {rules.strip()};\n')
    # A published HTML update must not reuse cached CSS/JS from the previous design.
    for name, content in [('style.css', css), ('app.js', js), ('demo.js', demo), ('offline.js', offline), ('personalize.js', personalize), *extra.items()]:
        version = sha256(content.encode('utf-8')).hexdigest()[:12]
        html = html.replace(f'"{name}"', f'"{name}?v={version}"')
    return {'index.html': html, 'style.css': css, 'app.js': js, 'personalize.js': personalize, **extra}


def binary_folder(source):
    """Files copied byte-for-byte so the published preview has the same art and taillight frames."""
    return {path.name: path.read_bytes() for path in sorted(source.iterdir()) if path.is_file()}


BINARY_FOLDERS = {'maps': ROOT / 'hardware' / 'maps', 'art': ROOT / 'hardware' / 'art', 'taillights': ROOT / 'hardware' / 'ui' / 'taillights'}


def sync_binary(folder, expected, check):
    target = ROOT / 'preview' / folder
    target.mkdir(exist_ok=True)
    for name, content in expected.items():
        dest = target / name
        if check:
            if not dest.is_file() or dest.read_bytes() != content:
                raise SystemExit(f'Preview is out of date: {folder}/{name}. Run python tools/update_preview.py')
        else:
            dest.write_bytes(content)
    for stale in target.iterdir():
        if stale.name not in expected:
            if check:
                raise SystemExit(f'Preview has stale {folder}/{stale.name}. Run python tools/update_preview.py')
            stale.unlink()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in assets().items():
        dest = ROOT / 'preview' / name
        if args.check:
            if dest.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Preview is out of date: {name}. Run python tools/update_preview.py')
        else:
            dest.write_text(content, encoding='utf-8', newline='\n')
    for folder, source in BINARY_FOLDERS.items():
        sync_binary(folder, binary_folder(source), args.check)
    print('Preview assets match the production design.' if args.check else 'Updated standalone preview assets.')
